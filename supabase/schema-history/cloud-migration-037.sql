-- WHY 037 INSTEAD OF 035 (the brief's number):
--   The brief named cloud-migration-035.sql, but 035 + 036 were claimed by
--   the etymology generation feature ahead of this batch. Pre-deploy gate-4
--   enforces no gaps in the migration sequence, so the credibility-upgrade
--   migration claims 037 to keep the sequence contiguous. No semantic
--   difference — the file body is what the brief specified.
--
-- WHY THIS EXISTS:
--   The analogy_target_accurate verifier criterion catches obviously-wrong
--   analogy claims, but credibility erodes the second a domain expert
--   (the owner's pharmacist friend; the owner's father-in-law on ecology) reads
--   something that's structurally "right" but uses amateur terminology
--   ("the salt marsh evaporates the water" instead of "tidal flushing
--   renews the standing water"). The B+1.6 verifier upgrade adds a 7th
--   criterion + worked PASS/FAIL examples — but that's prevention. This
--   migration is the FEEDBACK LOOP: when a credibility miss slips through,
--   the owner gets a tap from the user, the rendering is marked stale
--   (reported_at), and the next personalize call regenerates it under the
--   stricter rubric (PROMPT_VERSION = 7).
--
-- analogy_reports schema:
--   - user_id           uuid references auth.users(id) — the reporter
--   - term_id           text references terms(id)
--   - rendering_long_definition  text — snapshot at report time
--   - rendering_why_it_matters   text — snapshot at report time
--   - rendering_example          text — snapshot at report time
--   - user_complaint    text (max 500 chars enforced by CHECK)
--   - created_at        timestamptz default now()
--   The rendering_* snapshot columns capture WHAT THE USER SAW. Without
--   them, a regen would erase the evidence and the owner couldn't review the
--   actual wording that didn't land. Storing the snapshot vs. joining to
--   user_term_renderings is deliberate — the rendering may have been
--   regenerated by the time the owner looks at the report.
--
-- user_term_renderings.reported_at:
--   Nullable timestamptz. Set by report-analogy-issue Edge Function the
--   moment a user taps "this analogy doesn't land →". The next
--   personalize-term call regenerates the row regardless of cache hit
--   (the function will be updated to treat non-null reported_at as a
--   regen trigger), and clears reported_at on successful regen so the
--   same rendering can be re-reported if the regen also misses.
--
-- RLS:
--   - analogy_reports: users insert their own rows (auth.uid() = user_id);
--     no SELECT policy for users (the owner reads via the dashboard using
--     service-role / `select * from analogy_reports order by created_at desc`).
--     Service role can do everything. Mirrors the `reports` table pattern
--     from cloud-init.sql.
--
-- IDEMPOTENT:
--   `create extension if not exists pgcrypto` is a no-op on re-apply.
--   `create table if not exists` skips re-creation.
--   `add column if not exists` is a no-op if the column exists.
--   `drop policy if exists` then `create policy` is clean re-apply.
--   `create or replace function` keeps the function OID stable.
--
-- ROLLBACK (if ever needed):
--   drop table if exists analogy_reports;
--   alter table user_term_renderings drop column if exists reported_at;
--   -- bump_profile_version_if_changed is a verbatim re-issue, no rollback needed.

create extension if not exists pgcrypto;

-- ────────────────────────────────────────────────────────────
-- Table — analogy_reports
-- ────────────────────────────────────────────────────────────

create table if not exists analogy_reports (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  term_id text not null references terms(id) on delete cascade,
  -- Snapshot of the rendering AT THE MOMENT the user reported it. The
  -- rendering itself may be regenerated immediately after the report,
  -- but the owner needs to know what wording actually didn't land.
  rendering_long_definition text not null,
  rendering_why_it_matters text not null,
  rendering_example text not null,
  -- Free-form complaint, capped at 500 chars (textarea maxlength on
  -- the client + this DB CHECK as defense-in-depth).
  user_complaint text not null check (char_length(user_complaint) <= 500),
  created_at timestamptz not null default now()
);

create index if not exists idx_analogy_reports_user
  on analogy_reports(user_id, created_at desc);
create index if not exists idx_analogy_reports_term
  on analogy_reports(term_id, created_at desc);

alter table analogy_reports enable row level security;

drop policy if exists "users insert own analogy reports" on analogy_reports;
create policy "users insert own analogy reports" on analogy_reports
  for insert with check (auth.uid() = user_id);

-- Service role can do everything (the owner reads via dashboard).
drop policy if exists "service role manages analogy reports" on analogy_reports;
create policy "service role manages analogy reports" on analogy_reports
  for all to service_role using (true);

-- ────────────────────────────────────────────────────────────
-- Column add — user_term_renderings.reported_at
-- ────────────────────────────────────────────────────────────

alter table user_term_renderings
  add column if not exists reported_at timestamptz;

