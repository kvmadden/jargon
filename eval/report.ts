// Corrected report on the 2026-10-30 run, computed from the saved rows, the
// labels file and the gate replay. No model call.
//
//   node eval/report.ts            # write eval/results/2026-10-30-report.md
//   node eval/report.ts --check    # exit 1 if the committed report is out of date
//
// The published summary (2026-10-30-summary.md) is frozen as it was written.
// This report corrects it: list-price costs, coverage from the data, and
// errors split into introduced and inherited, each with its denominator.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listPriceOfRow, rate } from './lib/eval-lib.ts';
import { buildReplay } from './replay-gate.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8');
const usd = (x: number) => `$${x.toFixed(2)}`;

export function buildReport(): string {
  const rows = read('eval/results/2026-10-30.jsonl').trim().split('\n').map((l) => JSON.parse(l));
  const meta = JSON.parse(read('eval/results/2026-10-30-meta.json'));
  const termsFile = JSON.parse(read('eval/data/terms.json'));
  const profilesFile = JSON.parse(read('eval/data/profiles.json'));
  const labels = JSON.parse(read('eval/data/labels-2026-10-30.json')).labels as Array<{
    run_id: string;
    label: string;
    origin: string | null;
    confirmed_by: string;
  }>;
  const replay = buildReplay();

  const n = rows.length;
  const accepted = rows.filter((r) => r.final_status !== 'fell_back_to_canonical');
  const firstTry = rows.filter((r) => r.final_status === 'accepted_first_try').length;
  const afterRetry = rows.filter((r) => r.final_status === 'accepted_after_retry').length;
  const fellBack = n - accepted.length;
  const terms = new Set(rows.map((r) => r.term_id));
  const byDifficulty = [1, 2, 3].map((d) => new Set(rows.filter((r) => r.difficulty === d).map((r) => r.term_id)).size);
  const plannedTermsDiff3 = termsFile.terms.filter((t: any) => t.difficulty === 3).length;
  const vocabEmpty = (profilesFile.known_vocabulary ?? []).length === 0;

  const parsedFirst = rows.filter((r) => r.pass1_verdict);
  const accFail = (c: string) => parsedFirst.filter((r) => r.pass1_verdict?.[c]?.result === 'fail').length;
  const finalVerdict = (r: any) => (r.final_status === 'accepted_first_try' ? r.pass1_verdict : r.retry_verdict);
  const analogyOutputs = accepted.filter((r) => finalVerdict(r)?.uses_analogy === true);

  const acceptedIds = new Set(accepted.map((r) => r.run_id));
  const lab = labels.filter((l) => acceptedIds.has(l.run_id));
  const introduced = lab.filter((l) => l.label === 'wrong' && l.origin === 'introduced');
  const inherited = lab.filter((l) => l.label === 'wrong' && l.origin === 'inherited');
  const inheritedExpert = inherited.filter((l) => l.confirmed_by.startsWith('Kevin'));
  const unsupported = lab.filter((l) => l.label === 'unsupported');
  const wrong = introduced.length + inherited.length;
  const expertConfirmed = lab.filter((l) => l.label === 'wrong' && l.confirmed_by.startsWith('Kevin')).length;
  const introducedInAnalogy = introduced.filter((l) => analogyOutputs.some((r) => r.run_id === l.run_id)).length;

  const asLogged = rows.reduce((s, r) => s + (r.cost_usd_incl_cache ?? 0), 0);
  const listPrice = rows.reduce((s, r) => s + listPriceOfRow(r), 0);
  const perItem = listPrice / n;

  const out: string[] = [];
  out.push('# 2026-10-30 personalize run: corrected report');
  out.push('');
  out.push('Generated by `node eval/report.ts` from `eval/results/2026-10-30.jsonl`, `eval/data/labels-2026-10-30.json` and the gate replay. **Development data**: the claim gate, the labels and the dev cases were all written after reading this run. Nothing here is a headline result.');
  out.push('');
  out.push('## Coverage');
  out.push('');
  out.push(`- Items run: ${n} of ${meta.planned_items} planned (${termsFile.terms.length} terms times ${profilesFile.profiles.length} profiles). The run stopped early on its budget guard.`);
  out.push(`- Distinct terms: ${terms.size} of ${termsFile.terms.length}. By difficulty: ${byDifficulty[0]} easy, ${byDifficulty[1]} medium, ${byDifficulty[2]} hard (the planned set had ${plannedTermsDiff3} hard terms, and none was reached).`);
  out.push(`- Profiles: ${profilesFile.profiles.length}, all written by the author (${profilesFile.profiles.map((p: any) => p.id).join(', ')}).`);
  out.push(`- Learned vocabulary: ${vocabEmpty ? 'empty for every profile, so the vocabulary rules were never exercised' : 'present'}.`);
  out.push('- One model family generated, verified and regenerated. No baseline was run.');
  out.push('');
  out.push('## Outcomes');
  out.push('');
  out.push(`- Accepted on the first try: ${rate(firstTry, n)}.`);
  out.push(`- Accepted after one regeneration: ${rate(afterRetry, n)}.`);
  out.push(`- Fell back to the canonical text: ${rate(fellBack, n)}.`);
  out.push('');
  out.push('Acceptance measures what the verifier passed, not what is true.');
  out.push('');
  out.push('## Errors in accepted outputs');
  out.push('');
  out.push(`Labels cover ${lab.length} of ${accepted.length} accepted outputs. The other ${accepted.length - lab.length} have no label, and unlabeled is not correct. Only ${expertConfirmed} labels were confirmed by a person, after an AI screen flagged them.`);
  out.push('');
  out.push('| | Count | Note |');
  out.push('| --- | --- | --- |');
  out.push(`| Introduced by the rewrite | ${introduced.length} | Expert-confirmed. The verifier caught ${rate(0, introduced.length)}. ${introducedInAnalogy} of ${introduced.length} sit in outputs the verifier marked as using an analogy. |`);
  out.push(`| Inherited from the canonical text | ${inherited.length} | ${inheritedExpert.length} expert-confirmed, ${inherited.length - inheritedExpert.length} from the AI read-through only. The verifier was told to trust the canonical text, so it could not catch these. |`);
  out.push(`| Shown to a learner and judged wrong | ${rate(wrong, accepted.length)} | A lower bound: ${accepted.length - lab.length} outputs were never labeled. |`);
  out.push(`| Repeating an unsupported claim | ${unsupported.length} more | Unpublished model sizes copied from the canonical text. |`);
  out.push('');
  out.push(`Outputs the verifier marked as using an analogy: ${rate(analogyOutputs.length, accepted.length)}.`);
  out.push(`In ${parsedFirst.length} parsed first-pass verdicts, \`technical_accuracy_preserved\` failed ${accFail('technical_accuracy_preserved')} times and \`analogy_target_accurate\` failed ${accFail('analogy_target_accurate')} times.`);
  out.push('');
  out.push('## Cost');
  out.push('');
  out.push(`- As logged: ${usd(asLogged)}. The run priced Opus 4.7 at $${meta.pricing_per_mtok.in} and $${meta.pricing_per_mtok.out} per million input and output tokens, three times the list price.`);
  out.push(`- At list price ($5 and $25, cache writes 1.25x, cache reads 0.1x), recomputed from the saved token counts: **${usd(listPrice)}**, about $${perItem.toFixed(3)} per item.`);
  out.push(`- The budget guard stopped the run at ${n} of ${meta.planned_items} items because it read the inflated figure (${usd(meta.spent_usd)} of a ${usd(meta.budget_usd)} budget). At list price all ${meta.planned_items} items would have cost about ${usd(perItem * meta.planned_items)}, well inside the budget.`);
  out.push('');
  out.push('## Claim gate replay (development result)');
  out.push('');
  out.push(`Today's claim gate, replayed over the ${replay.as_saved.accepted_outputs} saved accepted outputs. The gate was built from the ${replay.as_saved.introduced_errors.total} introduced errors in this run, and revised after review round 2, so holding them is expected and says nothing about new outputs.`);
  out.push('');
  out.push('The gate holds any sentence about the learner\'s field that the verifier does not quote as supported. The 2026-10-30 verifier (prompt version 9) never listed claims, so the replay is shown two ways:');
  out.push('');
  out.push('| | As saved (nothing vouched for) | Every sentence vouched for |');
  out.push('| --- | --- | --- |');
  const both = (k: 'introduced_errors' | 'inherited_wrong' | 'judged_correct' | 'unlabeled') =>
    `${replay.as_saved[k].held} of ${replay.as_saved[k].total} | ${replay.all_vouched[k].held} of ${replay.all_vouched[k].total}`;
  out.push(`| Accepted outputs held | ${rate(replay.as_saved.held_or_revise, replay.as_saved.accepted_outputs)} | ${rate(replay.all_vouched.held_or_revise, replay.all_vouched.accepted_outputs)} |`);
  out.push(`| Introduced errors held | ${both('introduced_errors')} |`);
  out.push(`| Inherited errors held | ${both('inherited_wrong')} |`);
  out.push(`| Outputs the AI read-through judged correct, held | ${both('judged_correct')} |`);
  out.push(`| Unlabeled outputs held | ${both('unlabeled')} |`);
  out.push('');
  out.push('A v10 verifier that quotes the field sentences it supports would land between the two columns. A hold shows the learner the canonical text, so its cost is lost personalization, not a wrong answer. The gate cannot tell that a claim is copied from a wrong canonical entry. The inherited errors it holds are held because they use field words or restrictions. Correcting the canonical text is the fix for those (docs/canonical-review.md).');
  out.push('');
  return out.join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const text = buildReport();
  const path = join(ROOT, 'eval/results/2026-10-30-report.md');
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // missing counts as out of date
    }
    if (current !== text) {
      console.error('eval/results/2026-10-30-report.md is out of date. Run node eval/report.ts');
      process.exit(1);
    }
    console.log('report is up to date');
  } else {
    writeFileSync(path, text);
    console.log(text);
  }
}
