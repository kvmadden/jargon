// Builds eval/results/<date>-summary.md from eval/results/<date>.jsonl.
//
//   node eval/summarize.mjs 2026-10-30
//
// Human-check sample selection is deterministic (no randomness): runs are
// sorted by run_id, then 10 accepted outputs and 5 rejected candidates are
// taken at evenly spaced positions. Reviewer notes, written by a person after
// reading the sample, are merged in from eval/results/<date>-review.json
// (optional). Those notes are human judgment, not model output.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const date = process.argv[2];
if (!date) { console.error('usage: node eval/summarize.mjs <date>'); process.exit(2); }
const RES = join(ROOT, 'eval/results');
const rows = readFileSync(join(RES, `${date}.jsonl`), 'utf8').trim().split('\n').map((l) => JSON.parse(l))
  .sort((a, b) => a.run_id.localeCompare(b.run_id));
const meta = existsSync(join(RES, `${date}-meta.json`)) ? JSON.parse(readFileSync(join(RES, `${date}-meta.json`), 'utf8')) : null;
const reviewPath = join(RES, `${date}-review.json`);
const review = existsSync(reviewPath) ? JSON.parse(readFileSync(reviewPath, 'utf8')) : { notes: {} };
const terms = JSON.parse(readFileSync(join(ROOT, 'eval/data/terms.json'), 'utf8')).terms;
const termById = new Map(terms.map((t) => [t.id, t]));

const OUTCOMES = ['accepted_first_try', 'accepted_after_retry', 'fell_back_to_canonical'];
const CRITERIA = [
  'technical_accuracy_preserved', 'analogy_is_grounded', 'analogy_fits_the_term', 'example_reads_natural',
  'analogy_target_accurate', 'analogy_is_warranted', 'analogy_target_accurate_specific', 'vocabulary_within_reach',
];
const n = rows.length;
const pct = (k, d = n) => (d ? `${((100 * k) / d).toFixed(1)}%` : 'n/a');
const usd = (x) => `$${x.toFixed(4)}`;
const sum = (xs) => xs.reduce((s, x) => s + x, 0);
const pctl = (xs, p) => {
  if (!xs.length) return NaN;
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.ceil((p / 100) * s.length) - 1)]; // nearest rank
};
const sec = (ms) => `${(ms / 1000).toFixed(1)} s`;
const count = (pred) => rows.filter(pred).length;

const out = [];
const P = (s = '') => out.push(s);

P(`# personalize-term offline eval: ${date}`);
P();
P(`Generated by \`node eval/summarize.mjs ${date}\` from \`eval/results/${date}.jsonl\`.`);
P();
P('## Setup');
P();
P(`- Model: \`${rows[0]?.model}\` for every pass (generator, verifier, regenerator), prompt version ${rows[0]?.prompt_version}.`);
P(`- Runs completed: ${n}${meta ? ` of ${meta.planned_items} planned` : ''}${meta?.stopped_for_budget ? ' (stopped by the $' + meta.budget_usd + ' budget guard)' : ''}.`);
P('- Inputs: 40 seed terms (8 each: AI/LLM, data, security, APIs, cloud) x 3 synthetic profiles (hospital nurse, retail pharmacist, high-school teacher). Known vocabulary empty (cold start). Runs are interleaved by category and profile, so a budget stop leaves a near-balanced subset; per-group n is shown in each table.');
P('- Prompts, model ID, token limits, parsers and cost formula are imported from `supabase/functions/personalize-term/prompts.ts`, the same module the Edge Function uses.');
P('- Pricing: the function constants, $15 / $75 per million input / output tokens. "Formula" cost is what the function logs. "Incl. cache" adds prompt-cache writes (1.25x input rate) and reads (0.1x), which the function formula leaves out.');
P();

const tbl = (title, keyFn, keys) => {
  P(`### ${title}`);
  P();
  P('| group | n | accepted first try | accepted after retry | fell back to canonical |');
  P('|---|---|---|---|---|');
  for (const k of keys) {
    const g = rows.filter((r) => keyFn(r) === k);
    if (!g.length) continue;
    const c = (o) => g.filter((r) => r.final_status === o).length;
    P(`| ${k} | ${g.length} | ${c(OUTCOMES[0])} (${pct(c(OUTCOMES[0]), g.length)}) | ${c(OUTCOMES[1])} (${pct(c(OUTCOMES[1]), g.length)}) | ${c(OUTCOMES[2])} (${pct(c(OUTCOMES[2]), g.length)}) |`);
  }
  P();
};

P('## Outcomes');
P();
tbl('All runs', () => 'all', ['all']);
tbl('By category', (r) => r.category, ['ai-llm', 'data', 'security', 'apis', 'cloud']);
tbl('By profile', (r) => r.profile_id, ['nurse', 'pharmacist', 'teacher']);

const p1Pass = count((r) => r.pass1_verdict_overall === 'pass');
const retried = count((r) => r.retried);
const retryPass = count((r) => r.retry_verdict_overall === 'pass');
P('### Verifier verdicts');
P();
P('| measure | count | rate |');
P('|---|---|---|');
P(`| pass-1 verdict = pass | ${p1Pass} / ${n} | ${pct(p1Pass)} |`);
P(`| retry happened | ${retried} / ${n} | ${pct(retried)} |`);
P(`| retry verdict = pass | ${retryPass} / ${retried} | ${pct(retryPass, retried)} |`);
P(`| pass-1 candidate used an analogy (verifier's call) | ${count((r) => r.pass1_verdict?.uses_analogy === true)} / ${count((r) => r.pass1_verdict)} | ${pct(count((r) => r.pass1_verdict?.uses_analogy === true), count((r) => r.pass1_verdict))} |`);
P(`| final output used an analogy (accepted runs) | ${count((r) => r.final_status !== OUTCOMES[2] && (r.final_status === OUTCOMES[0] ? r.pass1_verdict : r.retry_verdict)?.uses_analogy)} / ${count((r) => r.final_status !== OUTCOMES[2])} | |`);
P();
P('### Which criteria failed');
P();
P('| criterion | pass-1 fails | retry fails |');
P('|---|---|---|');
for (const c of CRITERIA) {
  P(`| ${c} | ${count((r) => r.pass1_failed_criteria?.includes(c))} | ${count((r) => r.retry_failed_criteria?.includes(c))} |`);
}
P();
const errs = rows.filter((r) => r.error_text);
const maxTok = rows.filter((r) => Object.values(r.calls ?? {}).some((c) => c.stop_reason === 'max_tokens'));
P('### Errors and parse failures');
P();
P(`- Function status counts: ${Object.entries(rows.reduce((m, r) => ((m[r.function_final_status] = (m[r.function_final_status] ?? 0) + 1), m), {})).map(([k, v]) => `\`${k}\` ${v}`).join(', ')}.`);
P(`- Runs with an error or parse failure: ${errs.length}${errs.length ? ' (' + errs.map((r) => `${r.run_id}: ${String(r.error_text).slice(0, 80)}`).join('; ') + ')' : ''}.`);
P(`- Calls that hit max_tokens: ${maxTok.length}.`);
P(`- Transport retries (eval-only, HTTP 429/5xx): ${sum(rows.map((r) => r.transport_retries ?? 0))}.`);
P();

P('## Cost and latency');
P();
const costF = rows.map((r) => r.cost_usd_function_formula);
const costC = rows.map((r) => r.cost_usd_incl_cache);
const acc = rows.filter((r) => r.final_status !== OUTCOMES[2]);
P('| measure | function formula | incl. cache tokens |');
P('|---|---|---|');
P(`| total spend, ${n} runs | ${usd(sum(costF))} | ${usd(sum(costC))} |`);
P(`| mean cost per run | ${usd(sum(costF) / n)} | ${usd(sum(costC) / n)} |`);
P(`| cost per accepted personalization (total / accepted) | ${usd(sum(costF) / (acc.length || 1))} | ${usd(sum(costC) / (acc.length || 1))} |`);
for (const o of OUTCOMES) {
  const g = rows.filter((r) => r.final_status === o);
  if (g.length) P(`| mean cost, ${o.replaceAll('_', ' ')} (n=${g.length}) | ${usd(sum(g.map((r) => r.cost_usd_function_formula)) / g.length)} | ${usd(sum(g.map((r) => r.cost_usd_incl_cache)) / g.length)} |`);
}
P();
P(`Tokens: ${sum(rows.map((r) => r.tokens_in))} uncached input, ${sum(rows.map((r) => r.cache_write_tokens))} cache-write, ${sum(rows.map((r) => r.cache_read_tokens))} cache-read, ${sum(rows.map((r) => r.tokens_out))} output.`);
P();
P('Latency is the sum of model-call durations in a run (the calls are sequential, as in the function). It excludes network to Supabase, auth and cache writes.');
P();
P('| group | n | p50 | p95 | max |');
P('|---|---|---|---|---|');
const lat = (g, label) => { const xs = g.map((r) => r.latency_ms); if (xs.length) P(`| ${label} | ${xs.length} | ${sec(pctl(xs, 50))} | ${sec(pctl(xs, 95))} | ${sec(Math.max(...xs))} |`); };
lat(rows, 'all runs');
for (const o of OUTCOMES) lat(rows.filter((r) => r.final_status === o), o.replaceAll('_', ' '));
P();

// ─── Human-check sample ──────────────────────────────────────────────────────
const spaced = (xs, k) => (xs.length <= k ? xs : Array.from({ length: k }, (_, i) => xs[Math.floor((i * xs.length) / k)]));
const accSample = spaced(acc, 10);
const fellBack = rows.filter((r) => r.final_status === OUTCOMES[2] && (r.retry_candidate || r.pass1_candidate));
const rejPool = [
  ...fellBack.map((r) => ({ r, which: r.retry_candidate ? 'retry' : 'pass1' })),
  ...rows.filter((r) => r.final_status === OUTCOMES[1]).map((r) => ({ r, which: 'pass1' })),
];
const rejSample = spaced(fellBack.length >= 5 ? rejPool.slice(0, fellBack.length) : rejPool, 5);

const block = (label, c) => {
  P(`- **${label}**`);
  P(`  - long_definition: ${c.long_definition}`);
  P(`  - why_it_matters: ${c.why_it_matters}`);
  P(`  - example_in_sentence: ${c.example_in_sentence}`);
};
const noteFor = (key) => review.notes?.[key];

P('## Human-check sample');
P();
P(`Up to ten accepted outputs and five verifier-rejected candidates, verbatim. Selection: runs sorted by run_id, evenly spaced picks. ${review.reviewer ? `"Reviewer" lines: ${review.reviewer}` : '"Reviewer" lines are added from the review file after the run.'}`);
P();
P('### Accepted outputs');
P();
accSample.forEach((r, i) => {
  const t = termById.get(r.term_id);
  const v = r.final_status === OUTCOMES[0] ? r.pass1_verdict : r.retry_verdict;
  P(`#### A${i + 1}. \`${r.term}\` for the ${r.profile_label} (${r.final_status.replaceAll('_', ' ')})`);
  P();
  P(`- **Canonical long_definition:** ${t.long_definition}`);
  block('Accepted output', r.final_text);
  P(`- **Verifier:** uses_analogy=${v?.uses_analogy}; technical_accuracy_preserved: ${v?.technical_accuracy_preserved?.reasoning}; analogy_target_accurate: ${v?.analogy_target_accurate?.reasoning}`);
  const note = noteFor(`${r.run_id}::final`);
  P(`- **Reviewer:** ${note ? `${note.call}. ${note.note}` : '(not reviewed)'}`);
  P();
});
P('### Rejected candidates');
P();
if (rejSample.length < 5) {
  P(`Only ${rejPool.length} verifier-rejected candidate(s) exist in this run, so all are shown. Runs that fell back without a rejected candidate (for example, a parse failure) are listed under "Errors and parse failures".`);
  P();
}
rejSample.forEach(({ r, which }, i) => {
  const t = termById.get(r.term_id);
  const cand = which === 'retry' ? r.retry_candidate : r.pass1_candidate;
  const v = which === 'retry' ? r.retry_verdict : r.pass1_verdict;
  P(`#### R${i + 1}. \`${r.term}\` for the ${r.profile_label} (${which === 'retry' ? 'retry candidate, run fell back to canonical' : `pass-1 candidate, run ${r.final_status.replaceAll('_', ' ')}`})`);
  P();
  P(`- **Canonical long_definition:** ${t.long_definition}`);
  block('Rejected candidate', cand);
  const failed = CRITERIA.filter((c) => v?.[c]?.result === 'fail');
  P(`- **Verifier failed:** ${failed.map((c) => `${c}: ${v[c].reasoning}`).join(' | ') || '(unparseable verdict)'}`);
  const note = noteFor(`${r.run_id}::${which}`);
  P(`- **Reviewer:** ${note ? `${note.call}. ${note.note}` : '(not reviewed)'}`);
  P();
});

P('## Reviewer findings');
P();
if (!existsSync(reviewPath)) P('Not reviewed yet.');
const notes = Object.entries(review.notes ?? {});
const section = (title, calls) => {
  const xs = notes.filter(([, v]) => calls.includes(v.call));
  P(`### ${title} (${xs.length})`);
  P();
  if (!xs.length) P('None.');
  for (const [k, v] of xs) P(`- \`${k.replace(/::final$/, '')}\` (${v.call}): ${v.note}`);
  P();
};
if (existsSync(reviewPath)) {
  if (review.scope) { P(review.scope); P(); }
  section('Verifier misses: accepted output judged wrong', ['verifier miss', 'probable verifier miss']);
  section('Debatable accepts', ['debatable']);
  section('Errors inherited from the canonical seed text', ['canonical error inherited']);
  section('Questionable rejections', ['questionable reject']);
  if (review.extra?.length) {
    P('### Other observations');
    P();
    for (const e of review.extra) P(`- ${e}`);
    P();
  }
}

writeFileSync(join(RES, `${date}-summary.md`), out.join('\n'));
console.log(`wrote eval/results/${date}-summary.md (${n} runs, ${accSample.length} accepted + ${rejSample.length} rejected in sample)`);
