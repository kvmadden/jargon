export interface TermRow {
  id: string;
  term: string;
  pronunciation: string | null;
  path: PathId;
  /**
   * Stage B+1.5 — top-level domain bucket. Defaults to 'coding' for every
   * existing term via cloud-migration-018. When the second domain ships,
   * the path CHECK constraint expands to include the new domain's paths
   * AND each new term row carries domain = '<new>'.
   */
  domain: Domain;
  difficulty: 1 | 2 | 3;
  one_line_definition: string;
  long_definition: string;
  example_in_sentence: string;
  why_it_matters: string;
  related_terms: string[];
  prerequisites: string[];
  stretch_term: string | null;
  multiple_choice_distractors: [string, string, string];
  fill_in_blank_sentence: string | null;
  use_in_sentence_prompt: string;
  source: 'curated' | 'ai-generated';
  reviewed_at: string | null;
  reviewed_by: 'curator' | null;
  /**
   * Stage B+1.13 (cloud-migration-036) — "WHY IT'S CALLED THAT" prose.
   * Generated by the `generate-term-etymology` Edge Function via Opus 4.7
   * (multi-pass: generate → verify → optional regenerate). Plain prose,
   * 2-3 sentences, lowercase except proper nouns. NULL = not generated yet
   * (or generation failed verification). UI hides the section entirely
   * when null — no placeholder, no "etymology pending" copy.
   */
  etymology: string | null;
  /**
   * Stage B+1.13 (cloud-migration-036) — timestamp of the last successful
   * etymology write. Lets us regenerate selectively later (e.g. "regenerate
   * anything older than X" or "regenerate where prompt was bumped").
   * NULL while etymology is also NULL.
   */
  etymology_generated_at: string | null;
  created_at: string;
}

