/**
 * Per-user personalization profile. NO row = canonical-only mode (the user
 * skipped the onboarding profile step). `profile_version` is server-managed:
 * the `bump_profile_version_if_changed` trigger increments it whenever job,
 * education_level, interests, background_text, goals_extended,
 * encounter_contexts, heritage, or roles changes — that's the cache staleness
 * signal `user_term_renderings.profile_version_at_render` compares against.
 *
 * Stage B+1.1 added the `goals_extended` + `encounter_contexts` arrays —
 * filled by the 5-step onboarding wizard at /onboarding/profile. PROMPT_VERSION
 * bumped 1→2 (Edge Function) so existing renderings invalidate and pick up
 * the richer profile on next encounter.
 *
 * Stage B+1.2 added `heritage` (text) + `roles` (text[]) — wizard grew from
 * 5→7 steps. PROMPT_VERSION bumped 2→3 to pick up the new prompt slots.
 */
export interface UserProfileRow {
  user_id: string;
  /**
   * Optional guided curriculum accepted through a gift invite. This scopes
   * learning surfaces but is never used as an authorization signal.
   */
  guided_program_id: string | null;
  education_level: EducationLevel | null;
  job: string | null;
  interests: string[];
  background_text: string | null;
  /**
   * Stage B+1.10 (cloud-migration-031) — preferred display name. Surfaced in
   * greetings ("hi {display_name},") and welcome toasts. Capitalization is
   * preserved verbatim — never force-lowered or capitalized at write OR
   * render time. Null = not provided; greeting falls back to the
   * email-derived recipient_name (gift mode) or "friend" (self-onboarding).
   */
  display_name: string | null;
  /**
   * Stage B+1.11 (cloud-migration-032) — recipient's relationship to the
   * gifter (gift mode), or self-described relationship (self-onboarding via
   * Settings → edit profile). Copied from `gift_invites.relationship` at
   * accept time, then user-editable. One of the gift wizard's 9 chip options
   * OR a freeform "other" up to 60 chars. Null = not provided.
   */
  relationship: string | null;
  /**
   * Stage B+1.1 — multi-select reasons the user is here (e.g. "follow what
   * Claude Code is doing"). Empty array = not provided. Drives the "why" frame
   * in the personalize-term system prompt.
   *
   * B+1.10 NOTE: replaced by `goals_freeform` (textarea) in the onboarding
   * wizard. The column stays for backwards-compat / pre-B+1.10 data; new
   * writes land in `goals_freeform`. Personalization prompts prefer freeform
   * when present and fall back to this array's chip text.
   */
  goals_extended: string[];
  /**
   * Stage B+1.10 — freeform "what brings you to jargon?" textarea. Captures
   * the user's actual motivation in their own words rather than forcing a
   * pick from a chip grid. Preferred over `goals_extended` in personalization
   * prompts when non-null. Null = not provided.
   */
  goals_freeform: string | null;
  /**
   * Stage B+1.1 — multi-select surfaces where the user encounters these terms
   * (e.g. "Slack at work", "tech podcasts"). Empty array = not provided. Hint
   * for analogy freshness in the personalize-term system prompt.
   */
  encounter_contexts: string[];
  /**
   * Stage B+1.2 — free-form geography/culture/lineage line (e.g.
   * "Glasgow, Scotland", "Mexico → Texas"). Null = not provided. Widens the
   * analogy domain for the personalize prompt without overloading
   * background_text.
   */
  heritage: string | null;
  /**
   * Stage B+1.2 — multi-select roles that define the user (parent, mentor,
   * immigrant, veteran, freelancer, etc.). Empty array = not provided.
   * Orthogonal axis to job/interests in the personalize-term system prompt.
   */
  roles: string[];
  /**
   * Stage B+1.5 — which domain the user is actively learning. Today: always
   * 'coding'. When the second domain ships, onboarding adds a domain-pick
   * step and writes here. Switching domains MUST also invalidate
   * user_term_renderings (the personalized renderings are domain-specific
   * via the term-domain link). See MULTI-DOMAIN-EXTENSION.md §4.
   */
  active_domain: Domain;
  /**
   * Stage B+1.5 — the user's "lived" domain. Their day job, the vocabulary
   * they breathe in. Drives the right side of the translator badge
   * (`[active] → [home]`) and is the analogy-grounding signal for Opus
   * personalization. Distinct from `active_domain` — Kevin LEARNS coding but
   * LIVES in pharmacy; the translator goes `coding → pharmacy`. Today both
   * default to 'coding' so the badge collapses to identity (single icon,
   * no arrow). When the second domain ships, onboarding asks both questions.
   */
  home_domain: Domain;
  /**
   * Stage B+1.11 (cloud-migration-033) — 1-3 Phosphor icon slugs picked by
   * Opus 4.7 from this profile to visually represent the user's world.
   * Empty array = not picked yet (or Opus declined to pick from a sparse
   * profile). Allowlist + cap-at-3 enforced server-side; client-side
   * filtering is best-effort defense for legacy data.
   *
   * B+1.14: this column is now the FALLBACK render path for the home /
   * gift-accept badge surfaces. The new `lived_icon_url` column carries
   * a single AI-generated PNG that combines 2-3 motifs visually; when
   * non-null it takes precedence. lived_icons stays so legacy renders +
   * generation-failure paths still have something to show.
   */
  lived_icons: string[];
  /**
   * Stage B+1.14 (cloud-migration-038) — public Supabase Storage URL of
   * the AI-generated badge PNG (one circular flat-art mark combining 2-3
   * motifs from the profile). Set by the `generate-lived-icon-image`
   * Edge Function which runs Pass 1 (Opus picks motifs) → Pass 2 (Gemini
   * 2.5 Flash Image renders the PNG) → Pass 3 (uploads to lived-icons
   * bucket). Null = not generated yet OR generation failed; renderer
   * falls back to the legacy `lived_icons` Phosphor-strip path.
   *
   * The URL carries a `?t=<timestamp>` cache-buster so post-regeneration
   * fetches see the new bytes immediately even though the storage path
   * itself is stable per-user (`{user_id}.png`).
   */
  lived_icon_url: string | null;
  personalization_enabled: boolean;
  profile_version: number;
  created_at: string;
  updated_at: string;
}

/**
 * Cached Opus rendering of a canonical term entry through a user's profile.
 * Composite PK (user_id, term_id) — exactly one rendering per term per user.
 * Stale when profile_version_at_render < current user_profile.profile_version
 * OR prompt_version < CURRENT_PROMPT_VERSION (client constant in lib/data.ts)
 * OR model_used differs from current PERSONALIZE_MODEL
 * OR reported_at IS NOT NULL (B+1.6 — user reported "this analogy doesn't
 * land →" via the report-analogy-issue Edge Function; the next personalize
 * call regenerates it under the stricter B+1.6 rubric).
 */
export interface UserTermRenderingRow {
  user_id: string;
  term_id: string;
  long_definition: string;
  why_it_matters: string;
  example_in_sentence: string;
  rendered_at: string;
  profile_version_at_render: number;
  model_used: string;
  prompt_version: number;
  /**
   * B+1.6 (cloud-migration-037) — non-null = user tapped "this analogy
   * doesn't land →". Treated as a staleness signal by
   * fetchPersonalizedRendering — the next term-detail open fires a regen
   * regardless of profile/prompt/model versions. Cleared (set to null) by
   * the personalize-term Edge Function on successful regen.
   */
  reported_at: string | null;
  created_at: string;
}

