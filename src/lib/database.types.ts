interface TableShape<R, I, U> {
  Row: R;
  Insert: I;
  Update: U;
  Relationships: [];
}

export interface Database {
  public: {
    Tables: {
      terms: TableShape<
        TermRow,
        // B+1.13: etymology + etymology_generated_at default NULL in the DB
        // (cloud-migration-036). They're set asynchronously by the
        // generate-term-etymology Edge Function — INSERTs (seed data,
        // ingestion pipeline) shouldn't be forced to provide them.
        Omit<TermRow, 'created_at' | 'etymology' | 'etymology_generated_at'> & {
          created_at?: string;
          etymology?: string | null;
          etymology_generated_at?: string | null;
        },
        Partial<TermRow>
      >;
      user_progress: TableShape<
        UserProgressRow,
        Omit<UserProgressRow, 'id' | 'created_at' | 'updated_at'> & {
          id?: string;
          created_at?: string;
          updated_at?: string;
        },
        Partial<UserProgressRow>
      >;
      streak_log: TableShape<
        StreakLogRow,
        Omit<StreakLogRow, 'id' | 'created_at'> & {
          id?: string;
          created_at?: string;
        },
        Partial<StreakLogRow>
      >;
      settings: TableShape<
        SettingsRow,
        // last_seen_self_portrait_at + first_personalization_seen_at default
        // to NULL in the DB — INSERTs (initial settings row creation in
        // settings-store.ensureExists) shouldn't be forced to provide them.
        Omit<
          SettingsRow,
          'created_at' | 'updated_at' | 'last_seen_self_portrait_at' | 'first_personalization_seen_at'
        > & {
          created_at?: string;
          updated_at?: string;
          last_seen_self_portrait_at?: string | null;
          first_personalization_seen_at?: string | null;
        },
        Partial<SettingsRow>
      >;
      user_profile: TableShape<
        UserProfileRow,
        // Server-managed fields plus the four post-Stage-B+1 array/text columns
        // (DB defaults to '{}' / null) are optional on insert — callers may
        // upsert just the fields they touched in a given onboarding step.
        // W1 fix (code-reviewer): `interests` also has a DB default of '{}',
        // so it should be optional on insert too. Per-step upserts that touch
        // only heritage/roles shouldn't be forced to pass an empty interests
        // array.
        Omit<
          UserProfileRow,
          | 'created_at'
          | 'updated_at'
          | 'profile_version'
          | 'interests'
          | 'goals_extended'
          | 'encounter_contexts'
          | 'heritage'
          | 'roles'
          | 'display_name'
          | 'relationship'
          | 'lived_icons'
          | 'lived_icon_url'
          | 'guided_program_id'
        > & {
          created_at?: string;
          updated_at?: string;
          profile_version?: number;
          interests?: string[];
          goals_extended?: string[];
          encounter_contexts?: string[];
          heritage?: string | null;
          roles?: string[];
          display_name?: string | null;
          relationship?: string | null;
          lived_icons?: string[];
          lived_icon_url?: string | null;
          guided_program_id?: string | null;
        },
        Partial<UserProfileRow>
      >;
      user_term_renderings: TableShape<
        UserTermRenderingRow,
        // reported_at defaults to NULL in the DB, so it's optional on insert.
        Omit<UserTermRenderingRow, 'created_at' | 'rendered_at' | 'reported_at'> & {
          created_at?: string;
          rendered_at?: string;
          reported_at?: string | null;
        },
        Partial<UserTermRenderingRow>
      >;
    };
    // Stage A has no views or RPC functions yet; empty placeholders satisfy Supabase's
    // GenericSchema constraint without making us declare anything fake.
    Views: { [_ in never]: never };
    Functions: { [_ in never]: never };
    Enums: { [_ in never]: never };
    CompositeTypes: { [_ in never]: never };
  };
}

