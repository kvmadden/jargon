function buildLane(raw: RawLane): AtlasLane {
  return {
    id: raw.id,
    title: raw.title,
    frame: raw.frame,
    whyKevinCares: raw.whyKevinCares,
    concepts: raw.concepts.map(([id, term, plainMeaning, neighbors]) => ({
      id,
      laneId: raw.id,
      term,
      pronunciation: PRONUNCIATION_BY_CONCEPT_ID[id],
      plainMeaning,
      whyKevinCares: `${raw.whyKevinCares} This gives Kevin a clean place to put "${term}" when it shows up mid-conversation.`,
      status: SEEDED_CONCEPT_IDS.has(id)
        ? 'seeded'
        : 'candidate',
      neighbors: neighbors ?? [],
    })),
  };
}

export const CONCEPT_ATLAS: AtlasLane[] = RAW_ATLAS.map(buildLane);

export const allAtlasConcepts: AtlasConcept[] = CONCEPT_ATLAS.flatMap(
  (lane) => lane.concepts,
);

export function atlasLaneById(laneId: string): AtlasLane | null {
  return CONCEPT_ATLAS.find((lane) => lane.id === laneId) ?? null;
}

export function conceptAtlasSummary() {
  const statusCounts = allAtlasConcepts.reduce(
    (acc, concept) => {
      acc[concept.status] += 1;
      return acc;
    },
    {
      seeded: 0,
      candidate: 0,
      'priority-core': 0,
      'needs-curation': 0,
    } satisfies Record<ConceptStatus, number>,
  );

  return {
    totalLanes: CONCEPT_ATLAS.length,
    totalConcepts: allAtlasConcepts.length,
    statusCounts,
  };
}
